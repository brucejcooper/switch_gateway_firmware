/*
 * gen-assets.mjs — embed the built web UI into a C source file for the firmware.
 *
 * Walks the Vite output dir (dist/), gzip-compresses each file, and emits a
 * web_assets.c providing the web_assets_lookup() table declared in
 * src/net/web_assets.h. Assets are served straight from flash (XIP) with
 * Content-Encoding: gzip. Run as the `build` npm script's second step; the
 * output path comes from $GEN_OUT (CMake passes the build/generated location),
 * defaulting to ../build/generated/web_assets.c for a standalone `npm run build`.
 */

import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { dirname, join, relative, sep, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(here, '..');
const distDir = join(webRoot, 'dist');
const outPath = process.env.GEN_OUT
  ? resolve(process.env.GEN_OUT)
  : resolve(webRoot, '..', 'build', 'generated', 'web_assets.c');

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.js':   'application/javascript',
  '.css':  'text/css',
  '.json': 'application/json',
  '.svg':  'image/svg+xml',
  '.ico':  'image/x-icon',
  '.png':  'image/png',
  '.woff2':'font/woff2',
  '.map':  'application/json',
};
const mimeFor = (p) => MIME[p.slice(p.lastIndexOf('.')).toLowerCase()] || 'application/octet-stream';

function walk(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, acc);
    else acc.push(full);
  }
  return acc;
}

const files = walk(distDir).sort();
if (files.length === 0) {
  console.error(`gen-assets: no files in ${distDir} (run vite build first)`);
  process.exit(1);
}

let arrays = '';
let table = '';
let totalRaw = 0, totalGz = 0;

files.forEach((full, i) => {
  const raw = readFileSync(full);
  const gz = gzipSync(raw, { level: 9 });
  totalRaw += raw.length; totalGz += gz.length;
  // request path: "/<dist-relative path with forward slashes>"
  const rel = relative(distDir, full).split(sep).join('/');
  const path = '/' + rel;

  let bytes = '';
  for (let b = 0; b < gz.length; b++) {
    bytes += '0x' + gz[b].toString(16).padStart(2, '0') + ',';
    if ((b & 15) === 15) bytes += '\n';
  }
  arrays += `static const unsigned char a${i}[] = {\n${bytes}\n};\n`;
  table += `    { "${path}", "${mimeFor(path)}", a${i}, ${gz.length}, true },\n`;
});

const out = `/* AUTO-GENERATED by web/tools/gen-assets.mjs — do not edit.
 * ${files.length} asset(s), ${totalRaw} bytes raw -> ${totalGz} bytes gzip. */
#include "web_assets.h"
#include <string.h>

${arrays}
static const web_asset_t k_assets[] = {
${table}};

const web_asset_t *web_assets_lookup(const char *path) {
    if (strcmp(path, "/") == 0) path = "/index.html";
    for (size_t i = 0; i < sizeof k_assets / sizeof k_assets[0]; i++)
        if (strcmp(k_assets[i].path, path) == 0) return &k_assets[i];
    return NULL;
}
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out);
console.log(`gen-assets: ${files.length} asset(s), ${totalRaw} -> ${totalGz} B gzip -> ${outPath}`);
