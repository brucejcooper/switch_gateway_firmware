/*
 * fw_image.c — OTA image trailer verification. See fw_image.h for the wire
 * format and the hash/signature primitive note: this uses literal SHA-512
 * (crypto_sha512) + standard RFC 8032 Ed25519 (crypto_ed25519_check) from
 * Monocypher's optional monocypher-ed25519 extension, vendored verbatim
 * alongside the core library under lib/monocypher/.
 */

#include "fw_image.h"
#include "monocypher.h"
#include "monocypher-ed25519.h"

#include <string.h>
#include <stddef.h>

/* The trailer must be exactly
 * magic(4) + img_len(4) + build_ctr(4) + sha512(64) + sig(64) with no
 * compiler-inserted padding, since fw_verify() signs/verifies the
 * "magic | img_len | build_ctr | sha512" prefix by pointing straight at the
 * struct rather than re-packing it into a separate buffer. */
_Static_assert(sizeof(struct fw_trailer) == 4 + 4 + 4 + 64 + 64,
               "fw_trailer must be unpadded: 4+4+4+64+64 bytes");
_Static_assert(offsetof(struct fw_trailer, sig) == 4 + 4 + 4 + 64,
               "no padding expected before fw_trailer.sig");

/* DEV key — see the big warning in fw_image.h. Generated by
 * tools/fw_keygen.c (2026-07-05); matching private key at
 * tools/dev_privkey.bin (gitignored, never commit). Rotate for production. */
const uint8_t FW_PUBKEY[32] = {
    0x78, 0x35, 0x43, 0x40, 0x8F, 0xA0, 0x5E, 0x2A,
    0x2A, 0xD8, 0xBE, 0xE5, 0x39, 0xC1, 0xFB, 0x90,
    0x4F, 0x84, 0xF3, 0xC3, 0x52, 0xE9, 0xEE, 0xF4,
    0xC3, 0x74, 0x8B, 0x53, 0xDB, 0x12, 0x51, 0x69,
};

bool fw_trailer_at(const uint8_t *base, uint32_t total_len, struct fw_trailer *out) {
    if (!base || !out) return false;
    if (total_len < sizeof(struct fw_trailer)) return false;

    /* Copy out (rather than cast in place): base may not be 4-byte aligned
     * (e.g. a flash XIP pointer at an arbitrary offset), and this also
     * insulates callers' signed-prefix pointers from base's own alignment. */
    uint32_t trailer_off = total_len - (uint32_t)sizeof(struct fw_trailer);
    memcpy(out, base + trailer_off, sizeof *out);
    return true;
}

bool fw_verify(const uint8_t *buf, uint32_t total_len, const uint8_t *pubkey32) {
    if (!buf || !pubkey32) return false;

    struct fw_trailer trailer;
    if (!fw_trailer_at(buf, total_len, &trailer)) return false;
    uint32_t trailer_off = total_len - (uint32_t)sizeof(struct fw_trailer);

    if (trailer.magic != FW_TRAILER_MAGIC) return false;
    if (trailer.img_len != trailer_off) return false;   /* == total_len - sizeof(trailer) */

    /* SHA-512 digest of the image bytes. */
    uint8_t digest[64];
    crypto_sha512(digest, buf, trailer.img_len);
    if (crypto_verify64(digest, trailer.sha512) != 0) return false;

    /* Signature covers magic | img_len | build_ctr | sha512 — the trailer up
     * to (not including) sig itself. offsetof(..., sig) is statically
     * asserted above to equal that prefix's length, so &trailer can be used
     * directly as the signed message without re-packing it into a scratch
     * buffer. Note this expression auto-tracks any future trailer field
     * added before sig (it just did, for build_ctr) — no manual constant to
     * keep in sync here. */
    size_t signed_len = offsetof(struct fw_trailer, sig);
    if (crypto_ed25519_check(trailer.sig, pubkey32, (const uint8_t *)&trailer, signed_len) != 0)
        return false;

    return true;
}
