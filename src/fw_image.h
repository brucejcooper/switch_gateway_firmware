#pragma once
#include <stdint.h>
#include <stdbool.h>

/*
 * fw_image — OTA image trailer format + Monocypher-backed signature
 * verification (see CLAUDE.md / the OTA design doc for the full picture:
 * pull-based HTTP OTA, trust rooted in an ed25519 signature carried in an
 * IMAGE TRAILER appended to the artifact, not the manifest).
 *
 * Wire format: [image bytes][struct fw_trailer], trailer last. img_len is
 * the byte count of the image portion; the signed artifact's total length
 * is always img_len + sizeof(struct fw_trailer).
 *
 * ── Hash/signature primitive note ───────────────────────────────────────
 * As specified: SHA-512 digest + standard RFC 8032 Ed25519 signature, both
 * from vendored Monocypher. Monocypher's CORE monocypher.c/.h ships its own
 * EdDSA variant (crypto_eddsa_*) that hashes with BLAKE2b-512 internally —
 * it is not RFC 8032 Ed25519 and does not expose crypto_sha512 at all.
 * Literal SHA-512 + RFC 8032 Ed25519 (crypto_sha512, crypto_ed25519_sign/
 * _check) live in Monocypher's OPTIONAL extension pair
 * monocypher-ed25519.{c,h} — official upstream files from the very same
 * v4.0.2 release/tag as the core library (src/optional/monocypher-ed25519.
 * {c,h}), fetched from that tagged release and vendored verbatim
 * (byte-for-byte, unmodified — see lib/monocypher/monocypher-ed25519.{c,h})
 * alongside monocypher.c/.h. This is still "only vendored Monocypher" per
 * the hard rule — it is not hand-written or reconstructed crypto, just the
 * other half of the same upstream release that carries the primitives this
 * design actually names.
 *
 * This module therefore uses:
 *     digest:            crypto_sha512(hash, buf, n)
 *     sign / verify:     crypto_ed25519_sign / crypto_ed25519_check
 * which are standard, interoperable RFC 8032 Ed25519 with SHA-512 — a
 * signature produced by any conformant Ed25519 tool (openssl, libsodium,
 * signify, ...) over the same message will verify here, and vice versa.
 * ─────────────────────────────────────────────────────────────────────────
 */

#define FW_TRAILER_MAGIC 0x31545746u   /* "FWT1" */

struct fw_trailer {
    uint32_t magic;       /* FW_TRAILER_MAGIC */
    uint32_t img_len;     /* byte length of the image preceding this trailer */
    uint8_t  sha512[64];  /* SHA-512 digest (crypto_sha512) of the img_len
                            * image bytes */
    uint8_t  sig[64];     /* RFC 8032 Ed25519 (crypto_ed25519_sign) signature
                            * over the preceding fields: magic | img_len |
                            * sha512 */
};

/*
 * DEV key — 32-byte ed25519 public key generated by tools/fw_keygen.c
 * (2026-07-05). The matching 64-byte private key lives at
 * tools/dev_privkey.bin, which is gitignored and MUST NEVER be committed.
 * This key is fine for development/bench signing (tools/fw_sign.c) but
 * MUST be rotated (regenerate with fw_keygen, replace this array, reflash)
 * before any device ships/trusts OTA images in production — anyone with
 * this repo's history has the private key's provenance context, and dev
 * machines are not a secure key store.
 */
extern const uint8_t FW_PUBKEY[32];

/*
 * Copy the trailer out of the last sizeof(struct fw_trailer) bytes of a
 * total_len-byte artifact at base. Centralises the "is there even room for a
 * trailer" guard: returns false (leaving *out untouched) if total_len is too
 * short, true otherwise. Every other trailer-extraction call site in the
 * firmware (fw_verify() below, ota_stage.c, the bootloader's commit/rollback
 * path, and the host tests) should go through this rather than open-coding
 * `memcpy(&t, base + (total_len - sizeof t), sizeof t)` — that underflow
 * guard then lives in exactly one place.
 */
bool fw_trailer_at(const uint8_t *base, uint32_t total_len, struct fw_trailer *out);

/*
 * Locate the trailer at the end of buf (last sizeof(struct fw_trailer)
 * bytes of the total_len-byte artifact), and verify:
 *   1. magic matches FW_TRAILER_MAGIC;
 *   2. trailer.img_len + sizeof(struct fw_trailer) == total_len;
 *   3. the SHA-512 digest of buf[0 .. img_len) matches trailer.sha512
 *      (constant-time compare via crypto_verify64);
 *   4. the trailer's sig is a valid Ed25519 signature (under pubkey32) over
 *      magic | img_len | sha512.
 * Returns false immediately on the first mismatch (short-circuits — a
 * length/magic mismatch never touches the hash/signature machinery).
 * total_len must be at least sizeof(struct fw_trailer); anything shorter
 * fails closed (false).
 */
bool fw_verify(const uint8_t *buf, uint32_t total_len, const uint8_t *pubkey32);
